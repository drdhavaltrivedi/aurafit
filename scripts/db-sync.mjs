#!/usr/bin/env node
// Regenerates database artifacts derived from the single sources of truth:
//   packages/shared/schema.sql            -> supabase/migrations/<ts>_aurafit_init.sql (byte copy)
//   INITIAL_WORKOUT_DROPS (shared dist)   -> supabase/seed/demo_workout_drops.sql
// Run after editing schema.sql or the seed data: `npm run db:sync`
// (requires `npm run build:shared` first for the drop seed).
import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const MIGRATION = 'supabase/migrations/20261013120000_aurafit_init.sql';

mkdirSync(join(root, 'supabase/migrations'), { recursive: true });
copyFileSync(join(root, 'packages/shared/schema.sql'), join(root, MIGRATION));
console.log(`wrote ${MIGRATION}`);

const require = createRequire(import.meta.url);
const { INITIAL_WORKOUT_DROPS: drops } = require(join(root, 'packages/shared/dist/index.js'));
const q = (v) => `'${String(v).replace(/'/g, "''")}'`;

const creators = new Map();
for (const d of drops) {
  if (!creators.has(d.creatorHandle)) creators.set(d.creatorHandle, d);
}

const lines = [
  '-- OPTIONAL demo content: system creator profiles + the INITIAL_WORKOUT_DROPS catalog.',
  '-- GENERATED by scripts/db-sync.mjs from packages/shared/src/index.ts. Do not edit by hand.',
  '-- Not part of the migration. Run manually as an admin (SQL editor / psql / `supabase db query -f`),',
  '-- after supabase/migrations/*_aurafit_init.sql. Idempotent.',
  '-- Seed creators have auth_id NULL (they cannot sign in).',
  'BEGIN;',
  '',
  'INSERT INTO public.profiles (username, handle, role, avatar_url, title) VALUES',
  [...creators.values()]
    .map((d) => `    (${q(d.creatorName)}, ${q(d.creatorHandle)}, 'CREATOR', ${q(d.creatorAvatar)}, ${q(d.creatorBadge)})`)
    .join(',\n'),
  'ON CONFLICT (handle) DO NOTHING;',
  '',
  'INSERT INTO public.workout_drops (id, title, tagline, creator_id, vibe_tag, duration_minutes, calories_burn_estimate,',
  '    aura_multiplier, xp_points, difficulty, category, exercises, cover_from, cover_to, creator_badge,',
  '    likes_count, completions_count)',
  'SELECT v.id, v.title, v.tagline, p.id, v.vibe_tag, v.duration_minutes, v.calories, v.multiplier, v.xp,',
  '    v.difficulty::public.workout_difficulty_enum, v.category::public.workout_category_enum, v.exercises::jsonb,',
  '    v.cover_from, v.cover_to, v.badge, v.likes, v.completions',
  'FROM (VALUES',
  drops
    .map(
      (d) =>
        `    (${[
          q(d.id), q(d.title), q(d.tagline), q(d.creatorHandle), q(d.vibeTag), d.durationMinutes, d.caloriesBurnEstimate,
          d.auraMultiplier, d.xpPoints, q(d.difficulty), q(d.category), q(JSON.stringify(d.exercises)),
          q(d.coverGradient[0]), q(d.coverGradient[1]), q(d.creatorBadge), d.likesCount, d.completionsCount,
        ].join(', ')})`,
    )
    .join(',\n'),
  ') AS v(id, title, tagline, handle, vibe_tag, duration_minutes, calories, multiplier, xp, difficulty, category,',
  '       exercises, cover_from, cover_to, badge, likes, completions)',
  '-- auth_id IS NULL: never attach seed drops to a real user who happens to own the handle.',
  'JOIN public.profiles p ON p.handle = v.handle AND p.auth_id IS NULL',
  'ON CONFLICT (id) DO NOTHING;',
  '',
  'COMMIT;',
  '',
];
mkdirSync(join(root, 'supabase/seed'), { recursive: true });
writeFileSync(join(root, 'supabase/seed/demo_workout_drops.sql'), lines.join('\n'));
console.log('wrote supabase/seed/demo_workout_drops.sql');
