/**
 * Shared PGlite harness: a minimal stub of Supabase's `auth` schema, roles and
 * default privileges, so every migration in supabase/migrations/ can be applied,
 * in order, against real PostgreSQL (WASM).
 */
import { readdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { PGlite } from '@electric-sql/pglite';

export const MIGRATIONS_DIR = join(__dirname, '..', '..', '..', 'supabase', 'migrations');
export const SCHEMA_PATH = join(__dirname, '..', 'schema.sql');

/** Migrations in apply order (filename = timestamp prefix). */
export const MIGRATIONS: ReadonlyArray<{ file: string; sql: string }> = readdirSync(MIGRATIONS_DIR)
  .filter((f) => f.endsWith('.sql'))
  .sort()
  .map((file) => ({ file, sql: readFileSync(join(MIGRATIONS_DIR, file), 'utf8') }));

// Keep in sync with SCHEMA_HEADER in scripts/db-sync.mjs.
const SCHEMA_HEADER = [
  '-- GENERATED by scripts/db-sync.mjs. DO NOT EDIT.',
  '-- Cumulative AuraFit schema: every file in supabase/migrations/, concatenated in filename order.',
  '-- The migrations are the source of truth. To change the schema, add a NEW timestamped migration',
  '-- (never edit an applied one), then run `npm run db:sync`. Header comments inside the init',
  '-- migration below that call schema.sql the "single source of truth" predate this layout.',
  '',
].join('\n');

/** Expected content of packages/shared/schema.sql (same format as scripts/db-sync.mjs). */
export function bundleMigrations(migrations = MIGRATIONS): string {
  return SCHEMA_HEADER + migrations.map((m) => `\n-- >>> migration: ${m.file}\n${m.sql}`).join('');
}

export async function applyMigrations(db: PGlite): Promise<void> {
  for (const m of MIGRATIONS) {
    try {
      await db.exec(m.sql);
    } catch (e) {
      throw new Error(`${m.file}: ${(e as Error).message}`);
    }
  }
}

export const SUPABASE_STUB = `
  CREATE ROLE anon;
  CREATE ROLE authenticated;
  CREATE ROLE service_role BYPASSRLS;
  CREATE SCHEMA auth;
  CREATE TABLE auth.users (
    id uuid PRIMARY KEY,
    email text,
    raw_user_meta_data jsonb NOT NULL DEFAULT '{}'::jsonb,
    raw_app_meta_data jsonb NOT NULL DEFAULT '{}'::jsonb
  );
  CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS
    $$ SELECT nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
  GRANT USAGE ON SCHEMA auth TO anon, authenticated, service_role;
  GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
  GRANT EXECUTE ON FUNCTION auth.uid() TO anon, authenticated, service_role;
  -- Mirror Supabase's default privileges (verified on a live project): ALL on
  -- tables and EXECUTE on functions for every API role. The schema must narrow them.
  ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO anon, authenticated, service_role;
  ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON FUNCTIONS TO anon, authenticated, service_role;
`;

export async function createDb(): Promise<PGlite> {
  const db = new PGlite();
  await db.exec(SUPABASE_STUB);
  await applyMigrations(db);
  await applyMigrations(db); // every migration must be idempotent
  return db;
}

export type DbRole = 'authenticated' | 'anon' | 'service_role' | null;

export async function as(db: PGlite, role: DbRole, sub = ''): Promise<void> {
  await db.exec(role ? `RESET ROLE; SET ROLE ${role};` : 'RESET ROLE;');
  await db.query(`SELECT set_config('request.jwt.claim.sub', $1, false)`, [sub]);
}

export async function attempt(db: PGlite, sql: string, params: unknown[] = []): Promise<{ rows: unknown[]; error?: string }> {
  try {
    const r = await db.query(sql, params);
    return { rows: r.rows };
  } catch (e) {
    return { rows: [], error: (e as Error).message };
  }
}
